"""Deterministic plain-English readback of a validated spec (non-negotiable #6).

Generated by template code from the validated JSON — NEVER by the LLM call
that produced the spec — so the readback can never describe a different
strategy than the one that will run.
"""
from __future__ import annotations

from dsl.schema import Signal, StrategySpec
from dsl.universes import INDEX_NAMES, INDEX_PRESETS, PRESET_LABELS, resolve_preset

_REBALANCE_PHRASE = {
    "daily": "Every trading day",
    "weekly": "At the end of every week",
    "monthly": "At the end of every month",
    "quarterly": "At the end of every quarter",
    "annual": "At the end of every year",
}

_WEIGHTING_PHRASE = {
    "equal": "equally weighted",
    "rank": "weighted by rank (best pick largest)",
    "inverse_vol": "weighted inversely to 63-day volatility (calmer names get more)",
}

_OP_PHRASE = {"gt": "above", "gte": "at or above", "lt": "below",
              "lte": "at or below", "between": "between"}


def _days_phrase(days: int) -> str:
    mapping = {5: "1 week", 10: "2 weeks", 21: "1 month", 42: "2 months",
               63: "3 months", 126: "6 months", 189: "9 months",
               252: "12 months", 504: "2 years", 756: "3 years"}
    if days in mapping:
        return f"{days} trading days (≈{mapping[days]})"
    return f"{days} trading days"


def describe_signal(sig: Signal) -> str:
    if sig.type in ("return", "daily_return"):
        base = f"total return over the past {_days_phrase(sig.lookback_days or 1)}"
        if sig.skip_days:
            base += f", skipping the most recent {_days_phrase(sig.skip_days)}"
        return base
    if sig.type == "volatility":
        return f"annualized volatility over the past {_days_phrase(sig.lookback_days or 63)}"
    if sig.type == "sma_cross":
        return (f"the {sig.fast}-day moving average relative to the "
                f"{sig.slow}-day moving average")
    if sig.type == "drawdown_from_high":
        return f"decline from the highest close of the past {_days_phrase(sig.lookback_days or 252)}"
    if sig.type == "rsi":
        return f"{sig.lookback_days or 14}-day RSI"
    return sig.type


def _fmt_value(v) -> str:
    if isinstance(v, list):
        return f"{_fmt_value(v[0])} and {_fmt_value(v[1])}"
    if isinstance(v, (int, float)) and abs(v) < 1:
        return f"{v * 100:g}%"
    return f"{v:g}"


def readback(spec: StrategySpec) -> str:
    parts: list[str] = []
    universe_label = PRESET_LABELS.get(spec.universe.preset, spec.universe.preset)
    if spec.universe.preset in INDEX_PRESETS:
        # Say which universe will actually run: the index as it stood on each
        # rebalance date, or today's members standing in for the past.
        resolved = resolve_preset(spec.universe.preset, spec.window.start, spec.window.end)
        name = INDEX_NAMES[spec.universe.preset]
        universe_label = (f"the {name} members as of each rebalance date"
                          if resolved.point_in_time else f"the {name} as it stands today")
    if spec.universe.preset == "user_watchlist" and spec.universe.resolved_tickers:
        n = len(spec.universe.resolved_tickers)
        sample = ", ".join(spec.universe.resolved_tickers[:5])
        suffix = "…" if n > 5 else ""
        universe_label = f"your {n}-ticker watchlist ({sample}{suffix})"

    if spec.selection.static_allocation is not None:
        alloc = ", ".join(
            f"{p.weight:.0%} {p.ticker}" for p in spec.selection.static_allocation
        )
        parts.append(
            f"{_REBALANCE_PHRASE[spec.rebalance]}, rebalance a fixed allocation "
            f"of {alloc}."
        )
    else:
        sel = spec.selection
        direction = "highest" if sel.direction == "top" else "lowest"
        parts.append(
            f"{_REBALANCE_PHRASE[spec.rebalance]}, rank {universe_label} by "
            f"{describe_signal(sel.rank_by)} and hold the {sel.n} with the "
            f"{direction} values, {_WEIGHTING_PHRASE[spec.weighting]}."
        )

    for f in spec.filters:
        parts.append(
            f"Only consider names whose {describe_signal(f.signal)} is "
            f"{_OP_PHRASE[f.op]} {_fmt_value(f.value)}."
        )

    if spec.entry_exit.hold_days:
        parts.append(
            f"Each batch of buys is held for {spec.entry_exit.hold_days} trading "
            f"day{'s' if spec.entry_exit.hold_days > 1 else ''}; overlapping "
            f"batches split capital equally."
        )

    parts.append(
        f"Test window: {spec.window.start} to {spec.window.end}. Benchmark: "
        f"{spec.benchmark.replace('sixty_forty', '60/40 SPY/AGG')} — always "
        f"shown. Results are reported at 0, 5 and 20 bps trading costs; the "
        f"honest verdict uses the costed numbers."
    )
    return " ".join(parts)
