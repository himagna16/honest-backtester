"""English → strategy spec translation via the Claude API.

Hard rules (Section 2 + non-negotiables):
- The LLM returns a spec, clarifying questions, or a scope refusal — never a
  silent guess at a material parameter.
- Structured outputs make malformed JSON impossible at the transport level;
  the deterministic validator catches semantic problems and gets ONE
  self-repair round before surfacing the error.
- The plain-English readback shown to the user is generated by template code
  from the VALIDATED spec (dsl/readback.py) — never by this API call.
- Translations are cached in SQLite keyed by (prompt version, input hash);
  every attempt is logged and doubles as the future eval corpus (Gap #11).
"""
from __future__ import annotations

import hashlib
import json
from functools import lru_cache
from pathlib import Path
from typing import Literal

from pydantic import Field
from sqlalchemy import text as sql

from config import settings
from dsl.conventions import conventions_markdown
from dsl.readback import readback
from dsl.schema import StrategySpec, StrictModel
from dsl.validator import validate_spec
from store.db import get_engine
from store.events import log_event

PROMPT_VERSION = "translator_v1"
PROMPT_PATH = Path(__file__).parent / "prompts" / "translator_v1.md"


class ClarifyingQuestion(StrictModel):
    question: str
    options: list[str] = Field(default_factory=list)


class TranslatorReply(StrictModel):
    status: Literal["spec", "needs_clarification", "unsupported"]
    spec: StrategySpec | None = None
    assumptions: list[str] = Field(default_factory=list)
    questions: list[ClarifyingQuestion] = Field(default_factory=list)
    unsupported_reason: str | None = None


class TranslateError(Exception):
    def __init__(self, code: str, message: str):
        self.code = code
        super().__init__(message)


@lru_cache(maxsize=1)
def system_prompt() -> str:
    template = PROMPT_PATH.read_text()
    return template.replace("{CONVENTIONS_TABLE}", conventions_markdown())


def _input_hash(text: str) -> str:
    return hashlib.sha256(" ".join(text.split()).lower().encode()).hexdigest()


def _cache_get(input_hash: str) -> dict | None:
    with get_engine().begin() as conn:
        row = conn.execute(
            sql("SELECT response_json FROM translations WHERE "
                "prompt_version = :v AND input_hash = :h"),
            {"v": PROMPT_VERSION, "h": input_hash},
        ).fetchone()
    return json.loads(row[0]) if row else None


def _cache_put(input_hash: str, input_text: str, status: str, result: dict) -> None:
    with get_engine().begin() as conn:
        conn.execute(
            sql("INSERT OR REPLACE INTO translations "
                "(prompt_version, input_hash, input_text, status, response_json) "
                "VALUES (:v, :h, :t, :s, :r)"),
            {"v": PROMPT_VERSION, "h": input_hash, "t": input_text,
             "s": status, "r": json.dumps(result)},
        )


def _call_model(messages: list[dict]) -> TranslatorReply:
    import anthropic

    client = anthropic.Anthropic(
        api_key=settings.anthropic_api_key, timeout=90.0, max_retries=2
    )
    response = client.messages.parse(
        model=settings.llm_model,
        max_tokens=4000,
        output_config={"effort": "low"},
        system=[{
            "type": "text",
            "text": system_prompt(),
            "cache_control": {"type": "ephemeral"},
        }],
        messages=messages,
        output_format=TranslatorReply,
    )
    if response.stop_reason == "refusal":
        raise TranslateError(
            "model_refusal",
            "the model declined this request — rephrase the strategy idea",
        )
    parsed = response.parsed_output
    if parsed is None:
        raise TranslateError("parse_failed", "the model returned an unparsable reply")
    return parsed


def _finalize_spec(reply: TranslatorReply, user_text: str) -> dict:
    """Validate the spec; one self-repair round on failure (Section 2)."""
    assert reply.spec is not None
    result = validate_spec(reply.spec.model_dump(mode="json"))
    if not result.valid:
        repair_messages = [
            {"role": "user", "content": user_text},
            {"role": "assistant", "content": reply.model_dump_json()},
            {"role": "user", "content": (
                "That spec failed validation:\n- " + "\n- ".join(result.errors) +
                "\nReturn a corrected response. If the problem cannot be fixed "
                "within the schema, return status 'unsupported' or ask a "
                "clarifying question instead."
            )},
        ]
        reply = _call_model(repair_messages)
        if reply.status != "spec" or reply.spec is None:
            return _reply_to_result(reply)
        result = validate_spec(reply.spec.model_dump(mode="json"))
        if not result.valid:
            return {
                "status": "error",
                "errors": result.errors,
                "message": "the translation did not produce a valid spec — "
                           "try rephrasing with explicit numbers",
            }
    assert result.spec is not None
    return {
        "status": "spec",
        "spec": result.expanded,
        # Non-negotiable #6: readback comes from template code, never the LLM
        "readback": readback(result.spec),
        "assumptions": reply.assumptions,
        "warnings": result.warnings,
        "universe_size": len(result.resolved_universe),
    }


def _reply_to_result(reply: TranslatorReply) -> dict:
    if reply.status == "needs_clarification":
        return {
            "status": "needs_clarification",
            "questions": [q.model_dump() for q in reply.questions[:3]],
            "assumptions": reply.assumptions,
        }
    return {
        "status": "unsupported",
        "unsupported_reason": reply.unsupported_reason
        or "this idea needs capabilities outside the V0 engine",
    }


def translate(text: str, use_cache: bool = True) -> dict:
    text = text.strip()
    if not text:
        raise TranslateError("empty_input", "describe a strategy first")
    if len(text) > 4000:
        raise TranslateError("input_too_long", "keep the description under 4000 characters")
    if not settings.anthropic_api_key:
        raise TranslateError(
            "llm_not_configured",
            "plain-English translation needs ANTHROPIC_API_KEY in .env — "
            "everything else (engine, audits, journal) works without it",
        )

    h = _input_hash(text)
    if use_cache:
        cached = _cache_get(h)
        if cached is not None:
            log_event("translation_cache_hit", {"hash": h, "status": cached.get("status")})
            return {**cached, "cached": True}

    reply = _call_model([{"role": "user", "content": text}])
    if reply.status == "spec" and reply.spec is not None:
        result = _finalize_spec(reply, text)
    else:
        result = _reply_to_result(reply)

    event = {
        "spec": "translation_success",
        "needs_clarification": "translation_clarify",
        "unsupported": "translation_refusal",
        "error": "translation_error",
    }[result["status"]]
    log_event(event, {"hash": h})
    _cache_put(h, text, result["status"], result)
    return {**result, "cached": False}
